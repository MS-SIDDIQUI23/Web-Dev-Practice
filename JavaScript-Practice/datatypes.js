// 1. String (text)
let userName = "MS Siddiqui";
console.log("Type of userName:", typeof userName); // Output: string

// 2. Number (Integer & Float)
let userAge = 28;
let productPrice = 199.99;
console.log("Type of userAge:", typeof userAge); // Output: number

// 3. Boolean (True/False)
let isLogedIn = true;
console.log("Type of isLogedIn:", typeof isLogedIn); // Output: Boolean

// 4. Undefined (Value not assigned yet)
let futureGoal;
console.log("Type of futureGoal:", typeof futureGoal); // Output: undefined

// 5. Null (Empty value)
let selectedCar = null;
console.log("Value of selectedCar:", selectedCar);
// (Note: JavaScript ki purani bug ki waja se 'typeof null' object batata hai, yeh aik famous interview question hai!)